class Numbers:
    def __init__(self):
        self.d = {}

    def __setitem__(self, k, v):
        assert k.isalpha(), k  # LaTeX macro names: letters only
        self.d[k] = v

    def write(self, path):
        with open(path, "w") as f:
            f.write("% generated by scripts/paper/make_assets.py - do not edit\n")
            for k, v in sorted(self.d.items()):
                f.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")


def fmt(x, p=1):
    return f"{x:.{p}f}"


# --------------------------------------------------------------------------- dataset
def dataset_tables(m, seqs, out, N):
    trees = {}
    for s in seqs:
        trees.setdefault(s["tree"]["id"], s)
    rows = []
    heldout = set(m.get("splits", {}).get("heldout_trees", []))
    for tid, s in sorted(trees.items()):
        t = load_tree(os.path.join(s["tree_dir"], "canonical", "canonical_tree.npz"))
        meta = t["meta"]
        pot = meta["preset"]["pot"]["height"]
        rows.append({"id": tid, "preset": s["tree"]["preset_name"].replace("_", r"\_"), "type": NICE[meta["leaf_type"]],
                     "h": meta["height_m"] + pot, "leaves": meta["n_leaves"], "area": float(t["leaf_area"].sum()),
                     "tris": meta["n_leaf_tris"] + meta["n_wood_tris"], "split": "test" if tid in heldout else "train"})
    with open(os.path.join(out, "tab_trees.tex"), "w") as f:
        f.write("\\begin{tabular}{rllrrrrl}\n\\toprule\n"
                "ID & Preset & Leaf type & Height (m) & Leaves & Leaf area (m$^2$) & Triangles & Split \\\\\n\\midrule\n")
        for r in rows:
            f.write(f"{r['id']} & {r['preset']} & {r['type']} & {r['h']:.2f} & {r['leaves']:,} & {r['area']:.3f} & "
                    f"{r['tris']:,} & {r['split']} \\\\\n".replace(",", "{,}"))
        f.write("\\bottomrule\n\\end{tabular}\n")
    N["NTrees"] = len(rows)
    N["NLeavesMin"] = f"{min(r['leaves'] for r in rows):,}".replace(",", "{,}")
    N["NLeavesMax"] = f"{max(r['leaves'] for r in rows):,}".replace(",", "{,}")
    N["HeightMin"] = fmt(min(r["h"] for r in rows), 2)
    N["HeightMax"] = fmt(max(r["h"] for r in rows), 2)
    return rows


def validation_table(seqs, out, N):
    agg = defaultdict(list)
    n = 0
    for s in seqs:
        p = os.path.join(s["out_dir"], "validation.json")
        if not os.path.exists(p):
            continue
        n += 1
        c = json.load(open(p))["checks"]
        agg["self"].append(c["self_reprojection"]["max_px"])
        if "cross_reprojection" in c:
            agg["cross"].append(max(x["median_px"] for x in c["cross_reprojection"]["pairs"]))
        if "ground_plane" in c:
            for g in c["ground_plane"]["frames"]:
                agg["ground"].append(g.get("corner_median_m", g["median_m"]))
                if "corner_median_if_ray_distance_m" in g:
                    agg["ray"].append(g["corner_median_if_ray_distance_m"])
        if "depth_png_vs_exr" in c:
            agg["png"].append(c["depth_png_vs_exr"]["max_diff_m"])
        agg["ids"].append(c["leaf_ids"]["unknown_px"] + c["leaf_ids"]["mismatch_px"])
        if "flow_and_leaf_tracks" in c:
            for fr in c["flow_and_leaf_tracks"]["frames"]:
                for k in ("static", "leaves"):
                    if k in fr:
                        agg["flow_" + k].append(fr[k]["median_px"])
        agg["ok"].append(json.load(open(p))["ok"])
    N["NSeqValidated"] = n
    N["NSeqPassed"] = int(sum(agg["ok"]))
    N["ValSelfReprojPx"] = f"{max(agg['self']):.4f}"
    N["ValCrossReprojPx"] = f"{max(agg['cross']):.3f}"
    N["ValGroundUm"] = fmt(max(agg["ground"]) * 1e6, 0)
    N["ValRayMm"] = fmt(np.median(agg["ray"]) * 1000, 0)
    N["ValLeafFlowPx"] = f"{max(agg['flow_leaves']):.3f}"
    rows = [
        ("World position re-projects onto its own pixel centre", "max error", f"{max(agg['self']):.4f} px"),
        ("Cross-frame re-projection of exported depth (static geometry)", "worst median", f"{max(agg['cross']):.3f} px"),
        ("Back-projected floor lies on $z=0$ (image corners)", "worst median", f"{max(agg['ground']) * 1e6:.0f} $\\mu$m"),
        ("\\quad same test if depth were ray distance", "median", f"{np.median(agg['ray']) * 1000:.0f} mm"),
        ("16-bit PNG depth vs.\\ float EXR depth", "max difference", f"{max(agg['png']) * 1000:.2f} mm"),
        ("Leaf-ID pixels not in table / inconsistent with semantics", "total", f"{int(sum(agg['ids']))} px"),
        ("Per-leaf transforms predict rendered flow (leaf pixels)", "worst median", f"{max(agg['flow_leaves']):.3f} px"),
        ("Rendered flow of static geometry", "worst median", f"{max(agg['flow_static']):.3f} px"),
    ]
    with open(os.path.join(out, "tab_validation.tex"), "w") as f:
        f.write("\\begin{tabular}{llr}\n\\toprule\nCheck (all " + str(n) + " sequences) & Statistic & Value \\\\\n\\midrule\n")
        for a, b, c in rows:
            f.write(f"{a} & {b} & {c} \\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n")


# --------------------------------------------------------------------------- figures from data
def crop_to_content(img, sem, pad=12):
    ys, xs = np.nonzero(sem == 1)
    if len(ys) == 0:
        return img
    y0, y1 = max(ys.min() - pad, 0), min(ys.max() + pad, img.shape[0])
    x0, x1 = max(xs.min() - pad, 0), min(xs.max() + pad, img.shape[1])
    # include pot below the canopy
    pot = np.nonzero(sem == 3)
    if len(pot[0]):
        y1 = min(max(y1, pot[0].max() + pad), img.shape[0])
    return img[y0:y1, x0:x1]


def resize_h(img, h):
    import cv2
    return cv2.resize(img, (max(1, round(img.shape[1] * h / img.shape[0])), h), interpolation=cv2.INTER_AREA)


def fig_trees(seqs, out):
    import cv2
    tiles = []
    seen = set()
    for s in seqs:
        tid = s["tree"]["id"]
        if tid in seen or s["wind_level"] != "calm":
            continue
        seen.add(tid)
        d = s["out_dir"]
        rgb = read_png(os.path.join(d, "clean", "rgb", "00000.png"))[..., :3]
        sem = read_png(os.path.join(d, "clean", "semantic", "00000.png"))
        t = resize_h(crop_to_content(rgb, sem), 360)
        label = f"{tid}: {s['tree']['preset_name'].replace('_', ' ')}"
        (tw, _), _ = cv2.getTextSize(label, cv2.FONT_HERSHEY_SIMPLEX, 0.55, 1)
        extra = max(0, tw + 12 - (t.shape[1] + 8))
        t = cv2.copyMakeBorder(t, 0, 34, 4 + extra // 2, 4 + extra - extra // 2, cv2.BORDER_CONSTANT, value=(255, 255, 255))
        cv2.putText(t, label, (6, t.shape[0] - 10), cv2.FONT_HERSHEY_SIMPLEX, 0.55, (0, 0, 0), 1, cv2.LINE_AA)
        tiles.append(t)
    rows = [tiles[:5], tiles[5:10]]
    W = max(sum(t.shape[1] for t in r) for r in rows)
    lines = [np.concatenate(r + [np.full((r[0].shape[0], W - sum(t.shape[1] for t in r), 3), 255, np.uint8)], 1) for r in rows if r]
    write_png(os.path.join(out, "fig_trees.png"), np.concatenate(lines, 0))


def flow_to_rgb(flow, valid):
    import cv2
    mag, ang = cv2.cartToPolar(flow[..., 0].astype(np.float32), flow[..., 1].astype(np.float32))
    hsv = np.zeros(flow.shape[:2] + (3,), np.uint8)
    hsv[..., 0] = (ang * 90 / np.pi).astype(np.uint8)
    hsv[..., 1] = 255
    hsv[..., 2] = np.clip(mag / max(np.percentile(mag[valid], 99), 1e-6) * 255, 0, 255).astype(np.uint8) if valid.any() else 0
    rgb = cv2.cvtColor(hsv, cv2.COLOR_HSV2RGB)
    rgb[~valid] = 255
    return rgb


def depth_vis(z, lo=None, hi=None):
    import matplotlib
    v = z[z > 0]
    lo = lo if lo is not None else np.percentile(v, 1)
    hi = hi if hi is not None else np.percentile(v, 99)
    rgb = (matplotlib.colormaps["turbo"](np.clip((z - lo) / (hi - lo + 1e-9), 0, 1))[..., :3] * 255).astype(np.uint8)
    rgb[z <= 0] = 0
    return rgb


def fig_modalities(seqs, out, tree=1, level="high", frame=40):
    import cv2
    s = next(x for x in seqs if x["tree"]["id"] == tree and x["wind_level"] == level)
    d = s["out_dir"]
    f = f"{frame:05d}.png"
    rgb = read_png(os.path.join(d, "clean", "rgb", f))[..., :3]
    z = read_png(os.path.join(d, "clean", "depth", f)).astype(np.float32) * 1e-3
    zn = read_png(os.path.join(d, "noisy", "depth", f)).astype(np.float32) * 1e-3
    nrm = (read_png(os.path.join(d, "clean", "normal", f)).astype(np.float32) / 256).astype(np.uint8)
    lid = read_png(os.path.join(d, "clean", "leaf_id", f)).astype(np.int64)
    sem = read_png(os.path.join(d, "clean", "semantic", f))
    fl, fv = decode_flow_kitti(read_png(os.path.join(d, "clean", "flow", f)))
    lut = np.random.default_rng(3).integers(40, 255, (lid.max() + 1, 3)).astype(np.uint8)
    lut[0] = 0
    pal = np.array([[0, 0, 0], [60, 180, 60], [140, 85, 40], [215, 120, 60], [140, 140, 140], [210, 210, 230]], np.uint8)
    v = z[z > 0]
    lo, hi = np.percentile(v, 1), np.percentile(v, 99)
    panels = [("RGB", rgb), ("depth (z, m)", depth_vis(z, lo, hi)), ("normals (camera)", nrm), ("leaf IDs", lut[lid]),
              ("semantics", pal[np.minimum(sem, 5)]), ("optical flow", flow_to_rgb(fl, fv & (sem == 1))),
              ("noisy RGB", read_png(os.path.join(d, "noisy", "rgb", f))[..., :3]), ("noisy depth", depth_vis(zn, lo, hi))]
    ys, xs = np.nonzero(sem > 0) if (sem > 0).any() else (np.array([0]), np.array([0]))
    ys, xs = np.nonzero((sem == 1) | (sem == 2) | (sem == 3))
    y0, y1 = max(ys.min() - 15, 0), min(ys.max() + 15, rgb.shape[0])
    x0, x1 = max(xs.min() - 60, 0), min(xs.max() + 60, rgb.shape[1])
    tiles = []
    for name, im in panels:
        t = resize_h(np.ascontiguousarray(im[y0:y1, x0:x1]), 320)
        t = cv2.copyMakeBorder(t, 30, 3, 3, 3, cv2.BORDER_CONSTANT, value=(255, 255, 255))
        cv2.putText(t, name, (6, 22), cv2.FONT_HERSHEY_SIMPLEX, 0.65, (0, 0, 0), 1, cv2.LINE_AA)
        tiles.append(t)
    row = lambda ts: np.concatenate(ts, 1)  # noqa: E731
    write_png(os.path.join(out, "fig_modalities.png"), np.concatenate([row(tiles[:4]), row(tiles[4:])], 0))


def fig_wind_motion(m, seqs, out, N):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    levels = m["wind"]["levels"]
    data = defaultdict(dict)
    for s in seqs:
        p = os.path.join(s["out_dir"], "gt", "leaf_tracks.npz")
        if s["kind"] != "orbit" or not os.path.exists(p):
            continue
        z = np.load(p)
        tree = load_tree(os.path.join(s["tree_dir"], "canonical", "canonical_tree.npz"))
        c0 = tree["leaf_centroid"]
        disp = np.linalg.norm(z["centroid"] - c0[None], axis=2) * 1000
        R = z["transform_3x4"][..., :3].astype(np.float64)
        ang = np.degrees(np.arccos(np.clip((np.trace(R, axis1=2, axis2=3) - 1) / 2, -1, 1)))
        data[s["tree"]["id"]][s["wind_U"]] = (np.median(disp), np.percentile(disp, 95), np.median(ang), tree["meta"]["leaf_type"])
    fig, axs = plt.subplots(1, 2, figsize=(7.2, 2.8))
    cmap = {"broad": "#2a9d8f", "small": "#e9c46a", "compound": "#f4a261", "needle": "#264653"}
    for tid, d in sorted(data.items()):
        U = sorted(d)
        lt = d[U[0]][3]
        axs[0].plot(U, [d[u][0] for u in U], "o-", color=cmap[lt], lw=1.2, ms=3, label=f"{tid} ({lt})")
        axs[1].plot(U, [d[u][2] for u in U], "o-", color=cmap[lt], lw=1.2, ms=3)
    axs[0].set_ylabel("median leaf displacement [mm]")
    axs[1].set_ylabel("median leaf rotation [deg]")
    for ax in axs:
        ax.set_xlabel("canopy wind speed $U$ [m/s]")
        ax.grid(alpha=0.3)
    axs[0].legend(fontsize=6, ncol=2)
    fig.tight_layout()
    fig.savefig(os.path.join(out, "fig_wind_motion.pdf"))
    hi = max(levels.values())
    disp_hi = [d[hi][0] for d in data.values() if hi in d]
    rot_hi = [d[hi][2] for d in data.values() if hi in d]
    N["WindDispHiMin"], N["WindDispHiMax"] = fmt(min(disp_hi), 0), fmt(max(disp_hi), 0)
    N["WindRotHiMin"], N["WindRotHiMax"] = fmt(min(rot_hi), 0), fmt(max(rot_hi), 0)


