def load_results(paths):
    rows = []
    for p in paths:
        for r in csv.DictReader(open(p)):
            r["wind_U"] = float(r["wind_U"])
            r["seed"] = int(r.get("seed") or 0)
            rows.append(r)
    return rows


def results_assets(rows, levels, out, N):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from decompose_errors import decompose
    inv = {v: k for k, v in levels.items()}
    methods = sorted({r["method"] for r in rows})
    trees = sorted({r["tree"] for r in rows}, key=int)
    g = lambda r, k: float(r[k]) if r.get(k) not in (None, "") else np.nan  # noqa: E731

    # ---- per-condition table (mean over seeds, then over trees)
    keys = [("fscore", "F@5mm", 3, "up"), ("chamfer_mm", "CD [mm]", 1, "dn"), ("centroid_err_mm_median", "Centroid [mm]", 1, "dn"),
            ("leaf_area_rel_error", "Area err", 2, "dn"), ("leaf_angle_w1_deg", "Angle W1 [deg]", 1, "dn"),
            ("floater_frac", "Floaters", 2, "dn"), ("psnr", "PSNR [dB]", 1, "up")]
    conds = [(0.0, "clean"), (0.0, "noisy")] + [(u, "noisy") for u in sorted(set(levels.values())) if u > 0] + \
            [(u, "clean") for u in sorted(set(levels.values())) if u > 0]
    with open(os.path.join(out, "tab_results.tex"), "w") as f:
        f.write("\\begin{tabular}{ll" + "r" * len(keys) + "}\n\\toprule\nMethod & Condition & " +
                " & ".join(k[1] + ("$\\uparrow$" if k[3] == "up" else "$\\downarrow$") for k in keys) + " \\\\\n\\midrule\n")
        for m in methods:
            first = True
            for U, sns in conds:
                sel = [r for r in rows if r["method"] == m and r["wind_U"] == U and r["sensor"] == sns]
                if not sel:
                    continue
                per_tree = defaultdict(list)
                for r in sel:
                    per_tree[r["tree"]].append(r)
                vals = []
                for k, _, p, _ in keys:
                    tv = [np.nanmean([g(r, k) for r in rs]) for rs in per_tree.values()]
                    tv = [x for x in tv if np.isfinite(x)]
                    vals.append(f"{np.mean(tv):.{p}f}" if tv else "--")
                cond = f"{inv.get(U, U)} / {sns}"
                f.write(f"{m if first else ''} & {cond} & " + " & ".join(vals) + " \\\\\n")
                first = False
            f.write("\\midrule\n" if m != methods[-1] else "")
        f.write("\\bottomrule\n\\end{tabular}\n")
    N["NResultTrees"] = len(trees)
    N["NResultRuns"] = len(rows)
    N["NResultSeeds"] = len({r["seed"] for r in rows})

    # ---- decomposition table + figure
    dec = {met: decompose(rows, met, hb) for met, hb in [("fscore", True), ("chamfer_mm", False), ("centroid_err_mm_median", False)]}
    hi = max(levels.values())
    with open(os.path.join(out, "tab_decomp.tex"), "w") as f:
        f.write("\\begin{tabular}{llrrr}\n\\toprule\nMethod & Component & $\\Delta$F@5mm & $\\Delta$CD [mm] & $\\Delta$Centroid [mm] \\\\\n\\midrule\n")
        for m in methods:
            comps = [("method", "0", "Occlusion/method$^{\\dagger}$")] + [("sensor", "0", "Sensor")] + \
                    [("wind", f"{u:g}", f"Wind, $U={u:g}$ m/s") for u in sorted(set(levels.values())) if u > 0] + \
                    [("interaction", f"{hi:g}", f"Interaction, $U={hi:g}$")]
            for i, (c, u, lab) in enumerate(comps):
                cells = []
                for met in ("fscore", "chamfer_mm", "centroid_err_mm_median"):
                    v = dec[met].get(m, {}).get(c, {}).get(u)
                    if v is None:
                        cells.append("--")
                        continue
                    mu, sd = v["mean"], v["std"]
                    if met == "fscore" and c == "method":
                        mu = -mu  # report the absolute baseline F-score, not its negative
                    p = 3 if met == "fscore" else 1
                    val = f"{mu:+.{p}f}" if c != "method" else f"{mu:.{p}f}"
                    cells.append(val + (f" $\\pm$ {sd:.{p}f}" if v["n_trees"] > 1 else ""))
                f.write(f"{m if i == 0 else ''} & {lab} & " + " & ".join(cells) + " \\\\\n")
            f.write("\\midrule\n" if m != methods[-1] else "")
        f.write("\\bottomrule\n\\end{tabular}\n")
    sp = dec["fscore"].get("splatfacto", {})
    if sp:
        N["SpBaseF"] = fmt(-sp["method"]["0"]["mean"], 3)
        N["SpWindHiF"] = fmt(sp["wind"][f"{hi:g}"]["mean"], 3)
        N["SpSensorF"] = fmt(sp["sensor"]["0"]["mean"], 3)
        cd = dec["chamfer_mm"]["splatfacto"]
        N["SpBaseCD"] = fmt(cd["method"]["0"]["mean"], 1)
        N["SpWindHiCD"] = fmt(cd["wind"][f"{hi:g}"]["mean"], 1)
        N["SpSensorCD"] = fmt(cd["sensor"]["0"]["mean"], 1)
        N["SpInterHiCD"] = fmt(cd.get("interaction", {}).get(f"{hi:g}", {"mean": np.nan})["mean"], 1)
        ce = dec["centroid_err_mm_median"]["splatfacto"]
        N["SpWindHiCentroid"] = fmt(ce["wind"][f"{hi:g}"]["mean"], 1)
        N["SpSeedStdF"] = fmt(sp["_seed_noise_std"], 3) if sp.get("_seed_noise_std") else "n/a"

    nf = dec["fscore"].get("depth-nerfacto", {})
    if nf:
        N["NfBaseF"] = fmt(-nf["method"]["0"]["mean"], 3)
        N["NfWindHiF"] = fmt(nf["wind"][f"{hi:g}"]["mean"], 3)
        N["NfSensorF"] = fmt(nf["sensor"]["0"]["mean"], 3)
        N["NfBaseCD"] = fmt(dec["chamfer_mm"]["depth-nerfacto"]["method"]["0"]["mean"], 1)
        N["NfWindHiCD"] = fmt(dec["chamfer_mm"]["depth-nerfacto"]["wind"][f"{hi:g}"]["mean"], 1)

    # sensor effect for splatfacto: Gaussian count and precision/recall, calm clean vs calm noisy (mean over trees)
    def calm_mean(m, sensor, k):
        per_tree = defaultdict(list)
        for r in rows:
            if r["method"] == m and r["wind_U"] == 0 and r["sensor"] == sensor:
                per_tree[r["tree"]].append(g(r, k))
        return float(np.mean([np.nanmean(v) for v in per_tree.values()])) if per_tree else np.nan
    if any(r["method"] == "splatfacto" for r in rows):
        nc, nn = calm_mean("splatfacto", "clean", "n_recon_points_near_tree"), calm_mean("splatfacto", "noisy", "n_recon_points_near_tree")
        N["SpGaussClean"], N["SpGaussNoisy"] = f"{nc:,.0f}".replace(",", "{,}"), f"{nn:,.0f}".replace(",", "{,}")
        N["SpGaussRatio"] = fmt(nc / nn, 1)
        for k, nm in (("recall", "Rec"), ("precision", "Prec"), ("floater_frac", "Float")):
            N[f"Sp{nm}Clean"], N[f"Sp{nm}Noisy"] = fmt(calm_mean("splatfacto", "clean", k), 2), fmt(calm_mean("splatfacto", "noisy", k), 2)

    fig, axs = plt.subplots(1, 3, figsize=(7.4, 2.5))
    colors = {"splatfacto": "#e76f51", "depth-nerfacto": "#2a9d8f"}
    for ax, (met, lab) in zip(axs, [("fscore", "F@5mm drop"), ("chamfer_mm", "CD increase [mm]"), ("centroid_err_mm_median", "centroid error increase [mm]")]):
        for m in methods:
            w = dec[met].get(m, {}).get("wind", {})
            if not w:
                continue
            U = [0.0] + [float(u) for u in w]
            mu = [0.0] + [w[u]["mean"] for u in w]
            sd = [0.0] + [w[u]["std"] for u in w]
            ax.errorbar(U, mu, yerr=sd, marker="o", ms=3, capsize=2, lw=1.2, color=colors.get(m), label=m)
            s0 = dec[met][m]["sensor"]["0"]["mean"]
